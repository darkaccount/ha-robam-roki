"""The learned-controls generator: shared by the HA service and the CLI.

Both paths must write exactly the same controls section for the same learned
actions, so this test drives draft_from_properties (the HA path) and the CLI
draft command (the bundle path) and compares the generated bytes.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

import pytest
import yaml

MODULE_DIR = (
    Path(__file__).resolve().parents[1] / "custom_components" / "robam_roki"
)
DRAFT_PATH = MODULE_DIR / "draft.py"
CLI_PATH = Path(__file__).resolve().parents[1] / "tools" / "roki_cli.py"

DEVICE = {"dc": "RYYJ", "dt": "R8229"}
PROPERTIES = {"workStatus": 1, "level": 2}


def _load_module(name: str, path: Path) -> Any:
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


draft = _load_module("roki_draft_learn_test", DRAFT_PATH)
cli = _load_module("roki_cli_learn_test", CLI_PATH)

GROUPS = [
    {
        "frames": [
            {"command": 132, "body_hex": "01"},
            {"command": 132, "body_hex": "01"},
        ],
        "observed": {"workStatus": {"from": 0, "to": 1}},
    },
    {
        "frames": [{"command": 134, "body_hex": "02"}],
        "observed": {},
    },
]


def _loaded(result: Any) -> dict[str, Any]:
    return yaml.safe_load(result.profile_yaml)


def _controls_slice(text: str) -> str:
    marker = "# learned controls:"
    assert marker in text, text
    return text[text.index(marker) :]


# -- the generator -------------------------------------------------------


def test_the_captured_terminal_and_user_id_are_stripped() -> None:
    # The App marshals terminal type + its account user id before the
    # payload; the executor adds its own, so the drafter must drop them.
    groups = [
        {
            "frames": [{"command": 134, "body_hex": "0b3132333435363738393006"}],
            "observed": {},
        }
    ]
    document = _loaded(
        draft.draft_from_properties(DEVICE, PROPERTIES, learned_controls=groups)
    )
    assert document["controls"]["action_1"]["body_hex"] == "06"


def test_controls_are_generated_with_dedup_and_group_comments() -> None:
    result = draft.draft_from_properties(
        DEVICE, PROPERTIES, learned_controls=GROUPS
    )
    document = _loaded(result)
    assert document["controls"] == {
        "action_1": {
            "name": "开机",
            "kind": "mqtt",
            "command": 132,
            "body_hex": "01",
            "verified": False,
        },
        "action_2": {
            "name": "设置档位 2",
            "kind": "mqtt",
            "command": 134,
            "body_hex": "02",
            "verified": False,
        },
    }
    text = result.profile_yaml
    assert "# 本组 2 帧，去重后 1 条" in text
    assert "# 本组 1 帧，去重后 1 条" in text
    assert "命令 132，body 01；观察到 workStatus 0 → 1" in text
    assert "命令 134，body 02" in text
    # The suggested name is annotated as a guess, never presented as fact.
    assert text.count("# 名称是按设备变化推测的，建议改成 App 上显示的名字") == 2
    # The commented template is gone once real controls exist.
    assert "# controls:  # P2 reserved" not in text


def test_non_consecutive_identical_frames_are_merged() -> None:
    # Real-device captures interleaved read frames with the App's command, so
    # the same command+body can appear several times inside one group.
    groups = [
        {
            "frames": [
                {"command": 132, "body_hex": "01"},
                {"command": 134, "body_hex": "02"},
                {"command": 132, "body_hex": "01"},
                {"command": 136, "body_hex": "03"},
                {"command": 132, "body_hex": "01"},
            ],
            "observed": {},
        }
    ]
    document = _loaded(
        draft.draft_from_properties(
            DEVICE, PROPERTIES, learned_controls=groups
        )
    )
    assert list(document["controls"]) == ["action_1", "action_2", "action_3"]
    assert document["controls"]["action_1"]["command"] == 132
    assert document["controls"]["action_2"]["command"] == 134
    assert document["controls"]["action_3"]["command"] == 136
    text = draft.draft_from_properties(
        DEVICE, PROPERTIES, learned_controls=groups
    ).profile_yaml
    assert "# 本组 5 帧，去重后 3 条" in text


def test_the_same_command_in_two_groups_becomes_one_control() -> None:
    # Real capture: the user pressed the same App button twice, so the same
    # (command, body) landed in two different action groups.
    groups = [
        {
            "frames": [{"command": 132, "body_hex": "00"}],
            "observed": {"workStatus": {"from": 1, "to": 0}},
        },
        {
            "frames": [{"command": 132, "body_hex": "00"}],
            "observed": {},
        },
    ]
    result = draft.draft_from_properties(
        DEVICE, PROPERTIES, learned_controls=groups
    )
    document = _loaded(result)
    assert list(document["controls"]) == ["action_1"]
    assert document["controls"]["action_1"]["command"] == 132
    # The first occurrence wins, so its effect is the one documented.
    assert "观察到 workStatus 1 → 0" in result.profile_yaml



def test_a_flat_learn_stop_action_list_is_accepted() -> None:
    actions = [
        {
            "index": 1,
            "command": 136,
            "body_hex": "01",
            "observed": {},
            "truncated": False,
        }
    ]
    document = _loaded(
        draft.draft_from_properties(
            DEVICE, PROPERTIES, learned_controls=actions
        )
    )
    assert document["controls"]["action_1"]["command"] == 136


def test_no_learned_actions_keeps_the_commented_template() -> None:
    for learned in (None, []):
        result = draft.draft_from_properties(
            DEVICE, PROPERTIES, learned_controls=learned
        )
        assert "controls" not in _loaded(result)
        assert "# controls:" in result.profile_yaml


def test_learned_controls_combine_with_a_builtin_extends() -> None:
    result = draft.draft_from_properties(
        DEVICE,
        {"workStatus": 1, "level": 2, "custom": 5},
        builtin_driver="hood",
        builtin_keys={"work_status"},
        learned_controls=GROUPS,
    )
    document = _loaded(result)
    assert document["extends"] == "python:hood"
    assert "workStatus" not in document["sensors"]
    assert document["controls"]["action_1"]["kind"] == "mqtt"


# -- the suggested display names ----------------------------------------


def test_a_power_frame_names_the_control_from_the_gear_it_reported() -> None:
    groups = [
        {
            "frames": [{"command": 132, "body_hex": "02"}],
            "observed": {
                "workStatus": {"from": 0, "to": 1},
                "level": {"from": 0, "to": 2},
            },
        }
    ]
    document = _loaded(
        draft.draft_from_properties(DEVICE, PROPERTIES, learned_controls=groups)
    )
    assert document["controls"]["action_1"]["name"] == "开机（档位 2）"


@pytest.mark.parametrize(
    ("observed", "command", "expected"),
    [
        ({"workStatus": {"from": 0, "to": 1}}, 132, "开机"),
        ({"workStatus": {"from": 1, "to": 0}}, 132, "关机"),
        ({"level": {"from": 1, "to": 3}}, 134, "设置档位 3"),
        ({"lightStatus": {"from": 0, "to": 1}}, 136, "开灯"),
        ({"lightStatus": {"from": 1, "to": 0}}, 136, "关灯"),
        # No observed effect: fall back to the documented command meaning.
        ({}, 132, "开机/关机"),
        ({}, 134, "设置档位"),
        ({}, 136, "灯光开关"),
        ({}, 144, "设置倒计时"),
        # An undocumented command keeps a neutral, numbered label.
        ({}, 170, "动作 1"),
        # A change that carries no meaning for the hood also falls back.
        ({"faultCode": {"from": 0, "to": 1}}, 170, "动作 1"),
        # workStatus wins over a gear change: the gear is the power-on gear.
        ({"level": {"from": 0, "to": 6}, "workStatus": {"from": 0, "to": 1}}, 132, "开机（档位 6）"),
    ],
)
def test_control_names_follow_the_observed_effect(
    observed: dict[str, Any], command: int, expected: str
) -> None:
    assert (
        draft.suggest_control_name(
            {"index": 1, "command": command, "observed": observed}
        )
        == expected
    )


@pytest.mark.parametrize(
    ("command", "body_hex", "expected"),
    [
        (134, "06", "设置档位 6"),
        (134, "03", "设置档位 3"),
        (132, "00", "关机"),
        (132, "01", "开机"),
        (136, "01", "开灯"),
        (136, "00", "关灯"),
        (140, "01", "动作 1"),
    ],
)
def test_the_payload_byte_names_controls_without_observations(
    command: int, body_hex: str, expected: str
) -> None:
    # The value byte is protocol evidence, so a command whose effect was not
    # observed in time still gets a meaningful default name.
    assert (
        draft.suggest_control_name(
            {"index": 1, "command": command, "body_hex": body_hex, "observed": {}}
        )
        == expected
    )

def test_a_nameless_suggestion_is_still_written_into_the_yaml() -> None:
    # A quoted name keeps the YAML valid even when the label carries spaces or
    # full-width brackets, and profiles.py accepts it as a display label.
    groups = [
        {
            "frames": [{"command": 132, "body_hex": "02"}],
            "observed": {
                "workStatus": {"from": 0, "to": 1},
                "level": {"from": 0, "to": 2},
            },
        }
    ]
    text = draft.draft_from_properties(
        DEVICE, PROPERTIES, learned_controls=groups
    ).profile_yaml
    assert '    name: "开机（档位 2）"' in text


# -- the CLI shares the generator ---------------------------------------


def _write_bundle(path: Path) -> None:
    bundle = {
        "schema": "roki-bundle/1",
        "device": {"dc": "RYYJ", "dt": "R8229", "transport": "mqtt"},
        "properties": dict(PROPERTIES),
        "frames": [],
        "observations": [],
        "truncated": False,
    }
    path.write_text(json.dumps(bundle), encoding="utf-8")


def test_the_ha_path_and_the_cli_path_write_identical_controls(
    tmp_path: Path,
) -> None:
    ha = draft.draft_from_properties(
        DEVICE, PROPERTIES, learned_controls=GROUPS
    )
    assert ha.profile_yaml

    bundle_path = tmp_path / "bundle.json"
    _write_bundle(bundle_path)
    learned_path = tmp_path / "learned.json"
    learned_path.write_text(json.dumps(GROUPS), encoding="utf-8")
    out_dir = tmp_path / "out"

    args = cli.build_parser().parse_args(
        [
            "draft",
            str(bundle_path),
            "--learned",
            str(learned_path),
            "--out",
            str(out_dir),
        ]
    )
    assert cli.cmd_draft(None, args) == 0
    cli_profile = (out_dir / "RYYJ-R8229.yaml").read_text(encoding="utf-8")
    assert _controls_slice(cli_profile) == _controls_slice(ha.profile_yaml)


def test_the_cli_accepts_a_learn_stop_style_actions_object(
    tmp_path: Path,
) -> None:
    bundle_path = tmp_path / "bundle.json"
    _write_bundle(bundle_path)
    learned_path = tmp_path / "learned.json"
    learned_path.write_text(
        json.dumps({"device_id": "R8229000000000000", "actions": [
            {"command": 132, "body_hex": "01", "observed": {}}
        ]}),
        encoding="utf-8",
    )
    out_dir = tmp_path / "out"
    args = cli.build_parser().parse_args(
        [
            "draft",
            str(bundle_path),
            "--learned",
            str(learned_path),
            "--out",
            str(out_dir),
        ]
    )
    assert cli.cmd_draft(None, args) == 0
    document = yaml.safe_load(
        (out_dir / "RYYJ-R8229.yaml").read_text(encoding="utf-8")
    )
    assert document["controls"]["action_1"]["body_hex"] == "01"


def test_the_cli_rejects_a_malformed_learned_file(tmp_path: Path) -> None:
    bundle_path = tmp_path / "bundle.json"
    _write_bundle(bundle_path)
    learned_path = tmp_path / "learned.json"
    learned_path.write_text("not json", encoding="utf-8")
    args = cli.build_parser().parse_args(
        ["draft", str(bundle_path), "--learned", str(learned_path)]
    )
    assert cli.cmd_draft(None, args) == 2

    learned_path.write_text(json.dumps({"nope": 1}), encoding="utf-8")
    args = cli.build_parser().parse_args(
        [
            "draft",
            str(bundle_path),
            "--learned",
            str(learned_path),
            "--out",
            str(tmp_path / "out"),
        ]
    )
    assert cli.cmd_draft(None, args) == 2
